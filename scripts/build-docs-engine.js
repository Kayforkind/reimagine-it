#!/usr/bin/env node
/**
 * Build the browser bundles used by docs/index.html and extension/popup.html.
 *
 * The landing page and extension cannot import ../src at runtime. Concatenating
 * the dependency-free modules keeps both surfaces offline while preserving one
 * source of truth for the engine.
 */

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const inputs = ['src/extract.js', 'src/generate.js', 'src/auto.js'];
const outputs = [path.join(root, 'docs', 'engine.js'), path.join(root, 'extension', 'engine.js')];
const contents = inputs.map((file) => {
  const source = fs.readFileSync(path.join(root, file), 'utf8');
  return `/* ${file} */\n${source.trim()}\n`;
}).join('\n');
const expected = `/* Generated by scripts/build-docs-engine.js — do not edit by hand. */\n${contents}`;

if (process.argv.includes('--check')) {
  const stale = outputs.filter((output) => !fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== expected);
  if (stale.length) {
    console.error(stale.map((file) => `${path.relative(root, file)} is stale; run npm run build:docs`).join('\n'));
    process.exit(1);
  }
  console.log(outputs.map((file) => `${path.relative(root, file)} is current`).join('\n'));
} else {
  outputs.forEach((output) => fs.writeFileSync(output, expected, 'utf8'));
  console.log(`wrote ${outputs.map((file) => path.relative(root, file)).join(' and ')} from ${inputs.join(', ')}`);
}
